def _furniture(canvas, doc) -> None:
    canvas.saveState()
    canvas.setFont("UA", 7.5)
    canvas.setFillColor(MUTED)
    canvas.drawString(19 * mm, 10 * mm,
                      "Оцінювання різкості зображення в потоці — результати перевірки")
    canvas.drawRightString(A4[0] - 19 * mm, 10 * mm, str(canvas.getPageNumber()))
    canvas.setStrokeColor(RULE)
    canvas.setLineWidth(0.4)
    canvas.line(19 * mm, 13 * mm, A4[0] - 19 * mm, 13 * mm)
    canvas.restoreState()


